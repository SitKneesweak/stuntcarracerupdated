/*	Draw Bridge pieces MoveDrawBridge() owns, so the generator is not expected to match.		*/
static int IsRuntimeOwned( int track, int piece )
	{
	return (track == 5) && (piece == 51 || piece == 52);
	}

int main( void )
	{
	int failures = 0;

	for (int track = 0; track < OPP_SPEED_NUM_TRACKS; track++)
		{
		char path[256];
		snprintf(path, sizeof(path), "../Tracks/%s.bin", kNames[track]);

		FILE *f = fopen(path, "rb");
		if (f == NULL)
			{
			snprintf(path, sizeof(path), "Tracks/%s.bin", kNames[track]);
			f = fopen(path, "rb");
			}
		if (f == NULL)
			{
			printf("FAIL %-16s cannot open track data\n", kNames[track]);
			failures++;
			continue;
			}

		unsigned char raw[804];
		size_t got = fread(raw, 1, sizeof(raw), f);
		fclose(f);
		if (got != sizeof(raw))
			{
			printf("FAIL %-16s short track data (%zu bytes)\n", kNames[track], got);
			failures++;
			continue;
			}

		const int num_pieces = raw[0];
		const char *piece_angle = (const char *)(raw + 102);

		unsigned char speeds[MAX_PIECES];
		memset(speeds, 0, sizeof(speeds));
		BuildOpponentSpeedValues(track, num_pieces, piece_angle,
								 kCanBePutOn, kBaseSpeed[track], speeds);

		int bad = 0, skipped = 0;
		for (int i = 0; i < num_pieces; i++)
			{
			if (speeds[i] == kExpected[track][i])
				continue;
			if (IsRuntimeOwned(track, i))
				{
				skipped++;
				continue;
				}
			if (bad < 8)
				printf("     piece %2d: got 0x%02x want 0x%02x\n",
					   i, speeds[i], kExpected[track][i]);
			bad++;
			}

		if (bad)
			{
			printf("FAIL %-16s %d of %d pieces differ\n", kNames[track], bad, num_pieces);
			failures++;
			}
		else
			printf("ok   %-16s %2d pieces reproduced%s\n", kNames[track], num_pieces,
				   skipped ? " (2 runtime-owned pieces skipped)" : "");
		}

	if (failures)
		{
		printf("\n%d track(s) FAILED\n", failures);
		return 1;
		}

	printf("\nall %d tracks reproduce the Amiga tables\n", OPP_SPEED_NUM_TRACKS);
	return 0;
	}

/*	opponent_speed_test - checks the opponent speed generator against the Amiga.				*/
/*																							*/
/*	Opponent_Speeds.h rebuilds each track's per-piece speed table at the start of a race,	*/
/*	the way the Amiga does at srd1e..srd116.  The tables captured from a real Amiga run are	*/
/*	held in Opponent_Behaviour.cpp and copied below; with the right per-race base speed the	*/
/*	generator has to reproduce them exactly, which is what this checks.						*/
/*																							*/
/*	The one documented exception is Draw Bridge pieces 51 and 52.  MoveDrawBridge() rewrites	*/
/*	those two every time the bridge steps, and the capture was taken with it raised, so the	*/
/*	generator is not expected to match there.												*/
/*																							*/
/*		make -C tests && ./tests/opponent_speed_test											*/
/*	=========================================================================================	*/

